"""Resolve versioned shared tools and explicit project overrides without mutations.

The same bindings are frozen into queue jobs and consumed by tool adapters. No
tool is discovered by walking unrelated projects or silently replacing an
explicit override with the shared default.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import platform

from .common import WorkbenchError

LOCK_FILES = (
    "Tools/catalog.json", "Tools/node/package-lock.json", "Tools/rust.lock.json",
    "Tools/optional.lock.json",
    "skills/android-workbench/components/static-env/assets/toolchain.lock.json",
    "skills/android-workbench/components/static-env/assets/mcp.lock.json",
)


def shared_workspace(checkout):
    checkout = Path(checkout)
    fingerprint = hashlib.sha256()
    fingerprint.update((platform.system() + "/" + platform.machine()).encode())
    for name in LOCK_FILES:
        fingerprint.update(name.encode() + b"\0" + (checkout / name).read_bytes())
    base = Path(os.environ.get("ANDROID_WORKBENCH_TOOLCHAINS") or
                Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local/share")) /
                "android-workbench/toolchains").expanduser().resolve()
    return base / fingerprint.hexdigest()[:20]


def bindings(project, document=None):
    project = Path(project).expanduser().resolve()
    if document is None:
        config = project / "workbench.project.json"
        document = json.loads(config.read_text()) if config.is_file() else {}
    settings = document.get("toolchain", {})
    if not isinstance(settings, dict) or settings.get("mode", "project") not in {"shared", "project"}:
        raise WorkbenchError("toolchain must specify shared or project mode")
    checkout = (project / document.get("workbench_root", "android-workbench")).resolve()
    catalog = checkout / "Tools/catalog.json"
    if not catalog.is_file():
        return {}
    tools = json.loads(catalog.read_text())["tools"]
    default = shared_workspace(checkout) if settings.get("mode") == "shared" else project
    overrides = settings.get("overrides", {})
    if not isinstance(overrides, dict) or set(overrides) - {t["id"] for t in tools}:
        raise WorkbenchError("Unknown toolchain override")
    result = {}
    for item in tools:
        override = overrides.get(item["id"])
        if override is not None and (not isinstance(override, dict) or
                not isinstance(override.get("workspace"), str) or not override["workspace"]):
            raise WorkbenchError("Tool override requires an explicit workspace: " + item["id"])
        workspace = (project / Path(override["workspace"]).expanduser()).resolve() if override else default
        result[item["id"]] = {
            "workspace": str(workspace),
            "origin": "project_override" if override else "shared" if settings.get("mode") == "shared" else "project",
            "version": override.get("version", item["version"]) if override else item["version"],
        }
    return result


def binding(project, tool):
    # The scheduler's frozen bindings take precedence over a subsequently edited
    # manifest. These environment values are generated by normalize, not callers.
    frozen = os.environ.get("AWB_TOOLCHAIN_BINDINGS")
    current = json.loads(frozen) if frozen else bindings(project)
    return current.get(tool, {"workspace": str(Path(project).resolve()), "origin": "project"})


def default_workspace(project):
    frozen = os.environ.get('AWB_TOOLCHAIN_PROFILE')
    if frozen:
        return Path(frozen)
    project = Path(project).expanduser().resolve()
    config = project / 'workbench.project.json'
    document = json.loads(config.read_text()) if config.is_file() else {}
    if document.get('toolchain', {}).get('mode') == 'shared':
        return shared_workspace((project / document['workbench_root']).resolve())
    return project


def worker_environment(project, document):
    current = bindings(project, document)
    environment = dict(document.get("env", {}))
    if not current:
        return environment, current
    environment["AWB_TOOLCHAIN_BINDINGS"] = json.dumps(current, sort_keys=True)
    settings = document.get('toolchain', {})
    environment['AWB_TOOLCHAIN_PROFILE'] = str(
        shared_workspace((Path(project) / document['workbench_root']).resolve())
        if settings.get('mode') == 'shared' else Path(project).resolve())
    # Keep explicit project commands ahead of shared defaults. No global PATH or
    # shell profile is changed. Per-tool overrides are resolved by the adapters.
    ordered = sorted(current.values(), key=lambda b: b['origin'] != 'project_override')
    roots = list(dict.fromkeys(v["workspace"] for v in ordered))
    paths = [str(Path(p) / ".android-static/bin") for p in roots]
    state = Path(current['jdk']['workspace']) / ".android-static/state/jdk.json"
    if state.is_file():
        try:
            java = json.loads(state.read_text()).get("java_home")
        except (OSError, ValueError, AttributeError):
            java = None
        if java:
            paths.insert(0, str(Path(java) / "bin"))
            environment.setdefault("JAVA_HOME", java)
    environment["PATH"] = os.pathsep.join(paths + [environment.get("PATH", os.environ.get("PATH", os.defpath))])
    sdk = Path(current["sdk"]["workspace"]) / ".android-static/sdk"
    if sdk.is_dir():
        environment["ANDROID_HOME"] = environment["ANDROID_SDK_ROOT"] = str(sdk)
        environment["PATH"] = os.pathsep.join([
            str(sdk / "platform-tools"), str(sdk / "build-tools/36.0.0"),
            environment["PATH"],
        ])
    return environment, current


def preserve_legacy(project, document):
    """Register existing managed roots in place; never move their bytes."""
    project = Path(project)
    overrides = {}
    names = {
        "jadx": "jadx", "apktool": "apktool", "smali": "smali", "bundletool": "bundletool",
        "dex2jar": "d2j-dex2jar", "ghidra": "analyzeHeadless", "rizin": "rizin",
        "native-python": "native-python", "androguard": "androguard", "droidasc": "droidasc",
        "apkid": "apkid", "quark": "quark", "semgrep": "semgrep",
    }
    # Only explicitly registered environment roots are considered, never sibling
    # project discovery. An absent binding remains absent and is repaired shared.
    roots = [project]
    for location in document.get("environments", []):
        candidate = (project / location).resolve()
        if candidate.name == ".android-static":
            roots.append(candidate.parent)
    for root in dict.fromkeys(roots):
        for name, executable in names.items():
            if (root / ".android-static/bin" / executable).is_file():
                overrides.setdefault(name, {"workspace": str(root)})
        if (root / ".android-static/state/jdk.json").is_file():
            overrides.setdefault("jdk", {"workspace": str(root)})
        if (root / ".android-static/sdk/build-tools").is_dir():
            overrides.setdefault("sdk", {"workspace": str(root)})
    return {"mode": "shared", "auto_install": True, "overrides": overrides}
